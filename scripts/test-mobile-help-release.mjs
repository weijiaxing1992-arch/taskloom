import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = file => readFileSync(new URL('../'+file,import.meta.url),'utf8')
const config=JSON.parse(read('portal/config.json'))
assert.equal(config.backendUrl,'https://taskloom.example.com/projects')
assert.equal(config.officialOrigin,'https://taskloom.example.com')
const sprint=read('src/views/Sprints.vue'),css=read('src/mobile-refinements.css')
assert.match(sprint,/sprint-related-toggle[^>]*primary:listMine[^>]*:aria-pressed="listMine"/)
assert.match(css,/\.btn\.sprint-related-toggle\[aria-pressed="true"\]/)
assert.match(css,/background: var\(--primary\) !important/)
assert.match(css,/font-weight: 700 !important/)
assert.match(css,/--ui-control-height: 44px/)
assert.match(css,/font-size: max\(16px, var\(--ui-font-body\)\)/)
assert.match(css,/env\(safe-area-inset-bottom\)/)
assert.match(css,/overscroll-behavior-x: contain/)
const main=read('src/main.ts')
assert(main.indexOf("import './mobile-refinements.css'")>main.indexOf("import './compact-page-layout.css'"))
assert.match(read('src/views/Help.vue'),/watch\(directoryOpen, open => \{ if \(open\) helpDirectoryExpanded.value = true \}\)/)
for(const topic of ['快速开始：找到当前模块的帮助','手机 H5 使用与布局','与我相关：筛选范围与选中状态','初始化账号与安全交付']) assert(read('docs/product-handbook.md').includes(topic))
assert(!read('portal/index.html').includes('访问本地后台'))
assert(!read('portal/index.html').includes('访问本机后台'))
console.log('Mobile layout contracts, selected state, help topics and official URLs passed.')
