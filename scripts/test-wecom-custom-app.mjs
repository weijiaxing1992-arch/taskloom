import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parse, compileScript, compileTemplate } from 'vue/compiler-sfc'

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const component = read('src/components/WecomCustomAppSettings.vue')
const server = read('cmd/server/wecom_custom_app.go')
const delivery = read('cmd/server/wecom_app_delivery.go')
const binding = read('src/components/WecomAppBinding.vue')
const profile = read('src/views/Profile.vue')
const organization = read('src/views/Organization.vue')
const navigation = read('src/organization.ts')
const docs = read('docs/wecom-custom-app.md')
const apiDocs = read('docs/internal-api-reference.md')

// Compile the actual administrator page template so a typo in the settings UI cannot
// silently turn the self-built-app route into a blank organization page.
const { descriptor } = parse(component)
const script = compileScript(descriptor, { id: 'wecom-custom-app' })
const template = compileTemplate({ source: descriptor.template.content, filename: 'src/components/WecomCustomAppSettings.vue', id: 'wecom-custom-app', compilerOptions: { bindingMetadata: script.bindings } })
assert.deepEqual(template.errors, [])

assert.match(navigation, /key:'wecom-app',name:'企业微信自建应用'/)
assert.match(organization, /to="\/organization\/wecom-app"/)
assert.match(organization, /section==='wecom-app'&&context\.isTenantAdmin/)
assert.match(component, /\/organization\/wecom-app/)
assert.match(component, /method:'PATCH'/)
assert.match(component, /version:form\.version/)
assert.match(component, /type="password"/)
assert.match(component, /autocomplete="new-password"/)
assert.match(component, /上线前核对清单/)
assert.match(component, /启用通知中心企业微信投递/)
assert.match(component, /DEVFLOW_WECOM_MODE/)
assert.match(component, /当前服务器处于模拟模式/)
assert.match(component, /WW_verify/)
assert.doesNotMatch(component, /localStorage|sessionStorage|fetch\(|XMLHttpRequest|window\.location\s*=/)

assert.match(server, /const wecomOfficialAPIBase = "https:\/\/qyapi\.weixin\.qq\.com"/)
assert.match(server, /validWecomAppOrigin/)
assert.match(server, /u\.Scheme == "https"/)
assert.match(server, /wecomAppVerifyFilePattern/)
assert.match(server, /devflow:wecom-custom-app:v1:/)
assert.match(server, /wecomAppStateCookie/)
assert.match(server, /notificationDeliveryEnabled/)
assert.match(server, /queue_wecom_app_notification/)
assert.match(server, /wecom_app_deliveries/)
assert.match(server, /externalCallsEnabled":\s+s\.Enabled && s\.DeliveryEnabled && s\.ready\(\) && wecomAppLiveMode\(\)/)
assert.doesNotMatch(server, /http\.DefaultClient/)
assert.match(delivery, /func wecomAppLiveMode\(\) bool \{ return env\("DEVFLOW_WECOM_MODE", "mock"\) == "live" \}/)
assert.match(delivery, /runWecomAppDeliveries/)
assert.match(delivery, /attempts>=6/)
assert.match(delivery, /wecomOfficialAPIBase \+ "\/cgi-bin\/message\/send/)
assert.doesNotMatch(delivery, /http\.DefaultClient/)
assert.match(binding, /'\/profile\/wecom-app\/'\+\(unbind\?'unbind':'bind'\)/)
assert.match(binding, /safeWecomAuthorization/)
assert.match(profile, /WecomAppBinding/)

assert.match(docs, /绝不会向企业微信发起网络请求/)
assert.match(docs, /DEVFLOW_WECOM_MODE=live/)
assert.match(docs, /可信域名/)
assert.match(docs, /企业可信 IP/)
assert.match(apiDocs, /\/api\/organization\/wecom-app/)
assert.match(apiDocs, /\/api\/profile\/wecom-app/)

console.log('企业微信自建应用：管理员入口、密钥掩码、可信域名校验、成员官方绑定、全通知队列与 mock/live 安全投递边界校验通过。')
